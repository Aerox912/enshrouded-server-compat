int checks=0;
void check(bool value,const char* label){++checks;if(!value)throw std::runtime_error(label);}
struct Block {std::uintptr_t address=0;std::vector<std::uint8_t> bytes;};
struct ImageFixture {std::uintptr_t base=0x140000000,bridge=0x70000000;std::vector<Block> blocks;};
bool fixture_read(void* context,std::uintptr_t address,void* output,std::size_t size) noexcept {
    auto* fixture=static_cast<ImageFixture*>(context);
    if(!fixture||!output)return false;
    for(const auto& block:fixture->blocks)if(block.address==address&&block.bytes.size()==size){
        std::memcpy(output,block.bytes.data(),size);return true;
    }
    return false;
}
